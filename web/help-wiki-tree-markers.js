function regions(width, height, boxes) {
  return boxes.map(([left, top, right, bottom, label]) => ({
    x: left * 100 / width,
    y: top * 100 / height,
    w: (right - left) * 100 / width,
    h: (bottom - top) * 100 / height,
    label,
  }));
}


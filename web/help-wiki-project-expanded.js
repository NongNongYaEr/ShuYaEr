import { projectExpandedPhotoSizes } from './help-wiki-project-expanded-markers.js';

function photo(name, alt, caption, markers) {
  const src = 'project-' + name + '.webp';
  const [width, height] = projectExpandedPhotoSizes[src];
  return { src, width, height, alt, caption, ...(markers ? { markers } : {}) };
}


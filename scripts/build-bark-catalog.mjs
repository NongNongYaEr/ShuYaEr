import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {deflateSync} from 'node:zlib';
import {fileURLToPath} from 'node:url';
import {generateBarkCompanionMaps} from '../web/bark-map-generator.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),qa=path.join(root,'.runtime/trunk-preset-expansion/bark'),records=JSON.parse(fs.readFileSync(path.join(qa,'inputs.json'),'utf8')),packed={};
const sha=data=>createHash('sha256').update(data).digest('hex');
function joinEdges(map,normal){
 const {width,height,data}=map;
 for(let axis=0;axis<2;axis++)for(let j=0;j<(axis?width:height);j++){
  const a=(axis?j:j*width)*4,b=(axis?(height-1)*width+j:j*width+width-1)*4,v=[0,1,2].map(k=>(data[a+k]+data[b+k])*.5);
  if(normal){const n=v.map(c=>c/255*2-1),length=Math.hypot(...n);for(let c=0;c<3;c++)v[c]=(n[c]/length*.5+.5)*255;}
  for(let c=0;c<3;c++)data[a+c]=data[b+c]=Math.round(v[c]);
 }
 return map;
}
for(const record of records){
 const color={width:512,height:512,data:new Uint8Array(fs.readFileSync(path.join(qa,record.key+'.color.rgba')))},pair=generateBarkCompanionMaps(color,record.generation),maps={color,normal:joinEdges(pair.normal,true),roughness:joinEdges(pair.roughness,false)};
 record.version=1;record.media_origin='existing_library_ai_generated';record.measured_pbr=false;record.preparation='Lanczos resize; paired edge blend; colour-derived OpenGL normal and roughness';record.rgba_sha256={};packed[record.style]={};
 for(const [slot,m]of Object.entries(maps)){record.rgba_sha256[slot]=sha(m.data);packed[record.style][slot]=deflateSync(m.data,{level:9}).toString('base64');if(slot!=='color')fs.writeFileSync(path.join(qa,record.key+'.'+slot+'.rgba'),m.data);}
}
const directory=path.join(root,'web/assets/bark'),file=path.join(directory,'bark-library-v2.js'),text='// Versioned bark catalog; generated by scripts/build-bark-catalog.py.\nexport const BARK_LIBRARY_CATALOG='+JSON.stringify(records)+';\nexport const BARK_LIBRARY_RGBA_ZLIB='+JSON.stringify(packed)+';\n';
if(fs.existsSync(file)&&fs.readFileSync(file,'utf8')!==text)throw Error('The versioned v2 catalog already differs; create a new version.');
fs.writeFileSync(file,text);fs.writeFileSync(path.join(directory,'bark-library-v2.source.json'),JSON.stringify({version:2,records},null,2));
console.log(JSON.stringify({styles:records.map(r=>r.style),bytes:Buffer.byteLength(text)}));

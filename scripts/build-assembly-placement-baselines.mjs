import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { placementSignature } from '../web/assembly-placement-signature.js';

// Read only the current formal tree catalog. Never use userSaved templates or archive projects.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), folder = path.join(root, 'assets/tree-template-library');
const records = {}, conflicts = new Set(); let templates = 0;
for (const name of fs.readdirSync(folder).filter(n => n.endsWith('.meta.json')).sort()) {
  const meta = JSON.parse(fs.readFileSync(path.join(folder, name), 'utf8').replace(/^\uFEFF/, ''));
  if (meta.userSaved || meta.batch !== 'ALL_PLANT_SAMPLE_V2') continue;
  const source = path.resolve(root, meta.path);
  if (!source.startsWith(folder + path.sep)) throw Error('Formal template outside current catalog');
  const doc = JSON.parse(fs.readFileSync(source, 'utf8').replace(/^\uFEFF/, '')); templates++;
  for (const instance of doc.authoring.branch_instances || []) {
    if (!instance.linked || !instance.asset_id) continue;
    const key = instance.asset_id + '/' + instance.id, signature = placementSignature(instance);
    if (records[key] && records[key] !== signature) conflicts.add(key);
    records[key] = signature;
  }
}
for (const key of conflicts) delete records[key];
fs.writeFileSync(path.join(root, 'web/assembly-placement-baselines.js'),
  '// Generated by scripts/build-assembly-placement-baselines.mjs from current formal templates.\n'
  + '// Placement fingerprints only: no meshes, textures, user projects or archive paths.\n'
  + 'export const AUTOMATIC_PLACEMENTS = ' + JSON.stringify(records) + ';\n');
console.log(JSON.stringify({ templates, records: Object.keys(records).length, ambiguous: conflicts.size }));

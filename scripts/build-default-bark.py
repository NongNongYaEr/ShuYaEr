"""Bake the existing library bark into a versioned, self-contained runtime asset.

The library image is read only. PBR relief is an estimate from its luminance,
not measured scan data. Browser and offline exports decode the same RGBA bytes.
"""
import base64
import hashlib
import json
from pathlib import Path
import zlib
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / '植物图片素材库/007_朴树_Celtis_sinensis/01_surface_tile.png'
OUTPUT = ROOT / 'web/assets/bark'
QA = ROOT / '.runtime/default-library-bark'
SIZE, BAND = 512, 32


def blend_edges(image):
    data = list(image.getdata())
    for axis in range(2):
        before = data[:]
        for row in range(SIZE):
            for i in range(BAND):
                weight = .5 * (1 - i / (BAND - 1)) ** 2
                a = row * SIZE + i if axis == 0 else i * SIZE + row
                b = row * SIZE + SIZE - 1 - i if axis == 0 else (SIZE - 1 - i) * SIZE + row
                left, right = before[a], before[b]
                data[a] = tuple(round(x * (1 - weight) + y * weight) for x, y in zip(left, right))
                data[b] = tuple(round(y * (1 - weight) + x * weight) for x, y in zip(left, right))
    result = Image.new('RGBA', (SIZE, SIZE))
    result.putdata(data)
    return result


def build():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    QA.mkdir(parents=True, exist_ok=True)
    color = blend_edges(Image.open(SOURCE).convert('RGBA').resize((SIZE, SIZE), Image.Resampling.LANCZOS))
    height = [p / 255 for p in color.convert('L').filter(ImageFilter.GaussianBlur(.7)).getdata()]
    sample = lambda x, y: height[(y % SIZE) * SIZE + x % SIZE]
    normal, rough = [], []
    for y in range(SIZE):
        for x in range(SIZE):
            dx, dy = (sample(x-1, y) - sample(x+1, y)) * 3, (sample(x, y-1) - sample(x, y+1)) * 3
            length = (dx*dx + dy*dy + 1) ** .5
            normal.append((round((dx/length*.5+.5)*255), round((dy/length*.5+.5)*255), round((1/length*.5+.5)*255), 255))
            value = round((.89 + (.5-sample(x, y))*.12) * 255)
            rough.append((value, value, value, 255))
    n = Image.new('RGBA', (SIZE, SIZE)); n.putdata(normal)
    r = Image.new('RGBA', (SIZE, SIZE)); r.putdata(rough)
    # The periodic border has one common lighting value on both sides.
    for image in (n, r):
        for axis in range(2):
            pixels = image.load()
            for j in range(SIZE):
                a, b = ((0, j), (SIZE-1, j)) if axis == 0 else ((j, 0), (j, SIZE-1))
                value = tuple(round((x+y)/2) for x, y in zip(pixels[a], pixels[b]))
                pixels[a] = pixels[b] = value
    maps = {'color': color, 'normal': n, 'roughness': r}
    packed = {key: base64.b64encode(zlib.compress(image.tobytes(), 9)).decode('ascii') for key, image in maps.items()}
    provenance = {'version': 1, 'style': 'LIBRARY_CELTIS_V1', 'plant': '朴树',
                  'source': str(SOURCE.relative_to(ROOT)).replace('\\', '/'),
                  'source_sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
                  'media_origin': 'existing_library_ai_generated', 'size': SIZE,
                  'preparation': 'Lanczos resize; 32px paired edge blend; luminance-derived OpenGL normal and roughness',
                  'measured_pbr': False,
                  'rgba_sha256': {key: hashlib.sha256(image.tobytes()).hexdigest() for key, image in maps.items()}}
    module = '// Versioned library asset; generated by scripts/build-default-bark.py.\n'
    module += 'export const LIBRARY_BARK_PROVENANCE=' + json.dumps(provenance, ensure_ascii=False, separators=(',', ':')) + ';\n'
    module += 'export const LIBRARY_BARK_RGBA_ZLIB=' + json.dumps(packed, separators=(',', ':')) + ';\n'
    file = OUTPUT / 'celtis-bark-v1.js'
    if file.exists() and file.read_text(encoding='utf-8') != module:
        raise RuntimeError('The v1 asset already exists with different pixels; create a new version instead.')
    file.write_text(module, encoding='utf-8')
    (OUTPUT / 'celtis-bark-v1.source.json').write_text(json.dumps(provenance, ensure_ascii=False, indent=2), encoding='utf-8')
    for key, image in maps.items():
        image.save(QA / (key + '.png'))
    grid = Image.new('RGBA', (SIZE*2, SIZE*2))
    for x in range(2):
        for y in range(2):
            grid.paste(color, (x*SIZE, y*SIZE))
    grid.save(QA / '默认朴树皮_2x2平铺.png')
    print(json.dumps({'module': str(file), 'bytes': file.stat().st_size, **provenance}, ensure_ascii=False))


if __name__ == '__main__':
    build()
